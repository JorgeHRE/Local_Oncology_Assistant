"""Structural tests for the gastric cancer GMF module and its builder (no database needed).

The module is generated by `synthea/build_gastric_cancer.py`; the committed JSON must be exactly
what the builder produces, and the state machine must be well formed. The standard-code rule
(ADR-0001) is checked against the vocabulary in `tests/test_synthea_codes.py` (marker `db`).
"""

from __future__ import annotations

import importlib.util
import json
from types import ModuleType

import pytest

from oncology_assistant.db import REPO_ROOT

BUILDER_PATH = REPO_ROOT / "synthea" / "build_gastric_cancer.py"
MODULE_PATH = REPO_ROOT / "synthea" / "modules" / "gastric_cancer.json"
KEEP_PATH = REPO_ROOT / "synthea" / "keep" / "keep_gastric_cancer.json"

END_TYPES = {"Terminal", "Death"}


@pytest.fixture(scope="module")
def builder() -> ModuleType:
    """Load the builder script (synthea/ is not a package)."""
    spec = importlib.util.spec_from_file_location("build_gastric_cancer", BUILDER_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def states() -> dict[str, dict]:
    """States of the committed module."""
    return json.loads(MODULE_PATH.read_text(encoding="utf-8"))["states"]


def targets(state: dict) -> list[str]:
    """All transition targets of a state."""
    found = [state["direct_transition"]] if "direct_transition" in state else []
    for key in ("distributed_transition", "conditional_transition"):
        found += [branch["transition"] for branch in state.get(key, [])]
    return found


def test_committed_module_matches_builder(builder: ModuleType) -> None:
    """Editing the JSON by hand (or the builder without regenerating) must fail."""
    expected = builder.render(builder.build_module())
    assert MODULE_PATH.read_text(encoding="utf-8") == expected, (
        "synthea/modules/gastric_cancer.json is out of date: run "
        "python synthea/build_gastric_cancer.py"
    )


def test_every_transition_points_to_an_existing_state(states: dict[str, dict]) -> None:
    missing = {(name, t) for name, s in states.items() for t in targets(s) if t not in states}
    assert not missing


def test_every_state_is_reachable_and_has_a_way_out(states: dict[str, dict]) -> None:
    reached: set[str] = set()
    pending = ["Initial"]
    while pending:
        name = pending.pop()
        if name in reached:
            continue
        reached.add(name)
        pending.extend(targets(states[name]))
    assert reached == set(states)
    stuck = [n for n, s in states.items() if s["type"] not in END_TYPES and not targets(s)]
    assert not stuck


def test_distributions_add_up_to_one(states: dict[str, dict]) -> None:
    for name, state in states.items():
        if "distributed_transition" in state:
            total = sum(b["distribution"] for b in state["distributed_transition"])
            assert total == pytest.approx(1.0, abs=1e-4), name


def test_conditional_transitions_end_with_a_default(states: dict[str, dict]) -> None:
    """A conditional transition without a final unconditional branch can leave a person stuck."""
    for name, state in states.items():
        if "conditional_transition" in state:
            assert "condition" not in state["conditional_transition"][-1], name


def test_diagnosis_codes_are_the_ones_the_keep_module_looks_for(states: dict[str, dict]) -> None:
    emitted = {
        c["code"] for s in states.values() if s["type"] == "ConditionOnset" for c in s["codes"]
    }
    keep = json.loads(KEEP_PATH.read_text(encoding="utf-8"))
    kept = {
        c["code"]
        for branch in keep["states"]["Initial"]["conditional_transition"]
        if "condition" in branch
        for c in branch["condition"]["codes"]
    }
    assert emitted == kept == {"408647009", "187732006"}


def test_prior_state_conditions_name_real_states(states: dict[str, dict]) -> None:
    """A typo in a PriorState name silently never matches in Synthea."""

    def names(node: object) -> list[str]:
        if isinstance(node, dict):
            own = [node["name"]] if node.get("condition_type") == "PriorState" else []
            return own + [n for v in node.values() for n in names(v)]
        if isinstance(node, list):
            return [n for v in node for n in names(v)]
        return []

    unknown = {n for n in names(states) if n not in states}
    assert not unknown
